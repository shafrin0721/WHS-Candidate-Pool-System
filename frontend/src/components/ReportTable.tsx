import { FiDownload } from "react-icons/fi";
import type { RecentReport, ReportCandidate, ReportDefinition } from "../data/reportsData";

type ReportTableProps = {
  reports: ReportDefinition[];
  records: number;
  onDownload: (report: ReportDefinition, format: "PDF" | "Excel") => void;
};

type RecentReportsTableProps = {
  reports: RecentReport[];
  candidates: ReportCandidate[];
  onDownload: (report: RecentReport, candidates: ReportCandidate[]) => void;
};

export const ReportTable = ({ reports, records, onDownload }: ReportTableProps) => (
  <div className="admin-panel table-panel">
    <div className="panel-header">
      <h2>Reports List</h2>
    </div>
    <div className="table-scroll">
      <table className="admin-table">
        <thead>
          <tr>
            <th>Report</th>
            <th>Category</th>
            <th>Records</th>
            <th className="align-right">Actions</th>
          </tr>
        </thead>
        <tbody>
          {reports.map((report) => (
            <tr key={report.id}>
              <td>
                <p className="table-primary">{report.name}</p>
                <p className="table-secondary">{report.description}</p>
              </td>
              <td>{report.category}</td>
              <td className="table-strong">{records.toLocaleString("en-US")}</td>
              <td>
                <div className="table-actions">
                  <button
                    type="button"
                    onClick={() => onDownload(report, "PDF")}
                    className="admin-button admin-button-primary admin-button-small"
                  >
                    <FiDownload />
                    PDF
                  </button>
                  <button
                    type="button"
                    onClick={() => onDownload(report, "Excel")}
                    className="admin-button admin-button-secondary admin-button-small"
                  >
                    <FiDownload />
                    Excel
                  </button>
                </div>
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  </div>
);

export const RecentReportsTable = ({ reports, candidates, onDownload }: RecentReportsTableProps) => (
  <div className="admin-panel table-panel">
    <div className="panel-header">
      <h2>Recent Generated Reports</h2>
    </div>
    <div className="table-scroll">
      <table className="admin-table">
        <thead>
          <tr>
            <th>Report Name</th>
            <th>Type</th>
            <th>Generated On</th>
            <th>Generated By</th>
            <th className="align-right">Actions</th>
          </tr>
        </thead>
        <tbody>
          {reports.map((report) => (
            <tr key={report.id}>
              <td className="table-primary">{report.name}</td>
              <td>{report.type}</td>
              <td>{report.generatedAt}</td>
              <td>{report.generatedBy}</td>
              <td className="align-right">
                <button
                  type="button"
                  onClick={() => onDownload(report, candidates)}
                  className="icon-action-button"
                  aria-label={`Download ${report.name}`}
                >
                  <FiDownload />
                </button>
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  </div>
);
