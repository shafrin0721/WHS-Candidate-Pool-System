import { FiDownload } from "react-icons/fi";
import type { AdminCandidate, RecentReport } from "../../data/adminInsights";
import { exportCandidateReport } from "../../utils/exportReports";

type RecentReportsTableProps = {
  reports: RecentReport[];
  candidates: AdminCandidate[];
};

const RecentReportsTable = ({ reports, candidates }: RecentReportsTableProps) => (
  <div className="admin-panel table-panel">
    <div className="panel-header">
      <h2>Recent Generated Reports</h2>
    </div>
    <div className="table-scroll">
      <table className="admin-table">
        <thead>
          <tr>
            <th>Report Name</th>
            <th>Type</th>
            <th>Generated On</th>
            <th>Generated By</th>
            <th className="align-right">Actions</th>
          </tr>
        </thead>
        <tbody>
          {reports.map((report) => (
            <tr key={report.id}>
              <td className="table-primary">{report.name}</td>
              <td>{report.type}</td>
              <td>{report.generatedAt}</td>
              <td>Admin</td>
              <td className="align-right">
                <button
                  type="button"
                  onClick={() => exportCandidateReport(report, report.format, candidates)}
                  className="icon-action-button"
                  aria-label={`Download ${report.name}`}
                >
                  <FiDownload />
                </button>
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  </div>
);

export default RecentReportsTable;
